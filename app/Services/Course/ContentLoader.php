<?php

namespace App\Services\Course;

use App\Models\Exercise;
use App\Models\Word;
use RuntimeException;

/**
 * Reads the course content files (resources/content/{level}/lektion-NN/*.json) and turns them
 * into plain arrays: words (via VocabEntryFactory), grammar notes, conjugations, dialog lines,
 * readings and exercises. validate() reports structural problems before anything is seeded.
 */
class ContentLoader
{
    public function __construct(private readonly VocabEntryFactory $factory) {}

    public function basePath(string $level = 'A1'): string
    {
        return resource_path('content/'.strtolower($level));
    }

    /** @return string[] lesson directories in course order */
    public function lessonDirs(string $level = 'A1'): array
    {
        $dirs = glob($this->basePath($level).'/lektion-*', GLOB_ONLYDIR) ?: [];
        sort($dirs);

        return $dirs;
    }

    /** @return array<int, array<string, mixed>> */
    public function lessons(string $level = 'A1'): array
    {
        return array_map(fn (string $dir) => $this->load($dir), $this->lessonDirs($level));
    }

    /** @return array<string, mixed> */
    public function load(string $dir): array
    {
        $meta = $this->json($dir.'/meta.json', true);
        $vocab = $this->json($dir.'/vocab.json');
        $extras = $this->json($dir.'/extras.json');
        $grammar = $this->json($dir.'/grammar.json');
        $dialog = $this->json($dir.'/dialog.json');
        $readings = $this->json($dir.'/readings.json');
        $exercises = $this->json($dir.'/exercises.json');
        // Arabic translations overlay (resources/content/a1/arabic.json):
        // { "lektion-01": { "objectives": [...], "readings": {key: md}, "grammar": {key: md}, "revision": md } }
        $arabic = $this->json(dirname($dir).'/arabic.json')[basename($dir)] ?? [];
        foreach ($meta['objectives'] ?? [] as $i => $o) {
            $meta['objectives'][$i] = $o + ['ar' => $arabic['objectives'][$i] ?? null];
        }
        $meta['revision_ar_md'] = $arabic['revision'] ?? null;

        // Optional icon overlay for words without an emoji (generated by scripts/vocab-icons.mjs):
        // { "lektion-02": { "die Technik": "tabler:cpu", ... } }
        $overlay = $this->json(dirname($dir).'/icons.json');
        $icons = $overlay[basename($dir)] ?? [];

        $words = [];
        foreach ($vocab['groups'] ?? [] as $group) {
            foreach ($group['items'] ?? [] as $item) {
                $word = $this->factory->make($item, $group['category'], $group['type'] ?? null, $group['page'] ?? null);
                // same key as scripts/vocab-icons.mjs: raw entry without plural suffix and parentheses
                $key = trim(preg_replace('/\s+/u', ' ', preg_replace('/\s*\(.*?\)\s*/u', ' ', preg_replace('/,\s*.*$/u', '', $item[0]))));
                if ($word['image'] === null && isset($icons[$key])) {
                    $word['image'] = $this->factory->imagePath($icons[$key]);
                }
                $words[] = $word;
            }
        }

        $lines = [];
        foreach ($dialog['lines'] ?? [] as $i => $line) {
            $lines[] = $line + ['sort' => 100 + $i];
        }

        return [
            'dir' => $dir,
            'meta' => $meta,
            'words' => $words,
            'extras' => $extras['words'] ?? [],
            'grammar' => array_map(fn ($n) => $n + ['body_ar_md' => $arabic['grammar'][$n['key']] ?? null], $grammar['notes'] ?? []),
            'conjugations' => $grammar['conjugations'] ?? [],
            'dialog' => $lines,
            'dialog_english' => $dialog['english_for_existing'] ?? [],
            'readings' => array_map(fn ($r) => $r + ['translation_ar_md' => $arabic['readings'][$r['key']] ?? null], $readings['readings'] ?? []),
            'exercises' => $exercises['exercises'] ?? [],
        ];
    }

    /** @return string[] problems ("" when fine) */
    public function validate(array $lesson): array
    {
        $errors = [];
        $meta = $lesson['meta'];
        $label = 'Lektion '.($meta['number'] ?? '?');

        foreach (['level', 'number', 'slug', 'title', 'objectives'] as $k) {
            if (! isset($meta[$k]) || $meta[$k] === '' || $meta[$k] === []) {
                $errors[] = "$label: meta.$k missing";
            }
        }
        foreach ($meta['objectives'] ?? [] as $i => $o) {
            if (! isset($o['de'], $o['en'])) {
                $errors[] = "$label: objective #$i needs de + en";
            }
        }

        $seenWords = [];
        foreach ($lesson['words'] as $i => $w) {
            if (($w['german'] ?? '') === '' || ($w['arabic'] ?? '') === '' || ($w['english'] ?? '') === '') {
                $errors[] = "$label: word #$i needs german, arabic and english (".($w['german'] ?? '?').')';
            }
            if (! in_array($w['type'], Word::TYPES, true)) {
                $errors[] = "$label: word {$w['german']} has unknown type {$w['type']}";
            }
            $key = mb_strtolower($w['german']).'|'.$w['type'];
            if (isset($seenWords[$key])) {
                $errors[] = "$label: duplicate word {$w['german']} ({$w['type']})";
            }
            $seenWords[$key] = true;
            if (! empty($w['image']) && ! $this->imageAvailable($w['image'])) {
                $errors[] = "$label: image for {$w['german']} not found ({$w['image']})";
            }
        }

        foreach ($lesson['grammar'] as $i => $n) {
            if (empty($n['key']) || empty($n['title']) || empty($n['body_md'])) {
                $errors[] = "$label: grammar note #$i needs key, title, body_md";
            }
        }
        foreach ($lesson['conjugations'] as $c) {
            foreach (['german', 'ich', 'du', 'er_sie_es', 'wir', 'ihr', 'sie_Sie'] as $k) {
                if (empty($c[$k])) {
                    $errors[] = "$label: conjugation ".($c['german'] ?? '?')." misses $k";
                }
            }
        }
        foreach ($lesson['dialog'] as $i => $d) {
            if (empty($d['topic']) || empty($d['answer']) || empty($d['arabic']) || empty($d['english'])) {
                $errors[] = "$label: dialog line #$i needs topic, answer, arabic, english";
            }
        }
        foreach ($lesson['readings'] as $r) {
            if (empty($r['key']) || empty($r['title']) || empty($r['text_md'])) {
                $errors[] = "$label: reading needs key, title, text_md";

                continue;
            }
            foreach ($r['questions'] ?? [] as $qi => $q) {
                if (empty($q['q']) || empty($q['options']) || ! in_array($q['answer'] ?? null, $q['options'], true)) {
                    $errors[] = "$label: reading {$r['key']} question #$qi: answer must be one of the options";
                }
            }
        }

        $seen = [];
        foreach ($lesson['exercises'] as $e) {
            $k = $e['key'] ?? '?';
            if (isset($seen[$k])) {
                $errors[] = "$label: duplicate exercise key $k";
            }
            $seen[$k] = true;
            if (! in_array($e['type'] ?? null, Exercise::TYPES, true)) {
                $errors[] = "$label: exercise $k has unknown type ".($e['type'] ?? '?');

                continue;
            }
            if (! in_array($e['section'] ?? null, Exercise::SECTIONS, true)) {
                $errors[] = "$label: exercise $k has unknown section ".($e['section'] ?? '?');
            }
            if (empty($e['prompt'])) {
                $errors[] = "$label: exercise $k has no prompt";
            }
            $d = $e['data'] ?? [];
            $need = match ($e['type']) {
                'mc', 'dialog' => ['options', 'answer'],
                'listen' => ['text', 'options', 'answer'],
                'article' => ['word', 'answer'],
                'gap', 'translate', 'plural', 'conjugation' => ['accept'],
                'order' => ['tokens', 'answer'],
                'match' => ['pairs'],
                'write' => ['model_answer'],
                'reading' => ['reading_key'],
                default => [],
            };
            foreach ($need as $field) {
                if (empty($d[$field])) {
                    $errors[] = "$label: exercise $k ({$e['type']}) misses data.$field";
                }
            }
            if (in_array($e['type'], ['mc', 'dialog', 'listen'], true) && isset($d['options'], $d['answer']) && ! in_array($d['answer'], $d['options'], true)) {
                $errors[] = "$label: exercise $k: answer is not one of the options";
            }
            if ($e['type'] === 'article' && ! in_array($d['answer'] ?? null, ['der', 'die', 'das'], true)) {
                $errors[] = "$label: exercise $k: article answer must be der/die/das";
            }
            if ($e['type'] === 'order' && isset($d['tokens'], $d['answer'])) {
                $joined = $this->normalizeOrder(implode(' ', $d['tokens']));
                if ($joined !== $this->normalizeOrder($d['answer'])) {
                    $errors[] = "$label: exercise $k: tokens do not form the answer";
                }
            }
            if ($e['type'] === 'match' && count($d['pairs'] ?? []) < 3) {
                $errors[] = "$label: exercise $k: match needs at least 3 pairs";
            }
        }

        return $errors;
    }

    public function imageAvailable(string $publicPath): bool
    {
        if (is_file(public_path($publicPath))) {
            return true;
        }

        return is_file(base_path('node_modules/@twemoji/svg/'.basename($publicPath)));
    }

    private function normalizeOrder(string $s): string
    {
        $s = mb_strtolower($s);
        $s = preg_replace('/\s*([,.!?])\s*/u', '$1', $s);

        return preg_replace('/\s+/u', ' ', trim($s));
    }

    private function json(string $file, bool $required = false): array
    {
        if (! is_file($file)) {
            if ($required) {
                throw new RuntimeException("Content file missing: $file");
            }

            return [];
        }
        $data = json_decode(file_get_contents($file), true);
        if (! is_array($data)) {
            throw new RuntimeException("Invalid JSON in $file: ".json_last_error_msg());
        }

        return $data;
    }
}
